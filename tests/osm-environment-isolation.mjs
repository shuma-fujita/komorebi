import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const root=new URL('../komorebi3d/maps/',import.meta.url);
const asModule=async name=>'data:text/javascript;base64,'+Buffer.from(await readFile(new URL(name,root),'utf8')).toString('base64');
const configUrl=await asModule('osm-config.js');
const config=await import(configUrl);
const src=(await readFile(new URL('osm-api.js',root),'utf8')).replace('./osm-config.js?v=osm-environments-20261125',configUrl);
const {createOsmApi}=await import('data:text/javascript;base64,'+Buffer.from(src).toString('base64'));
const authSrc=(await readFile(new URL('osm-auth.js',root),'utf8')).replace('./osm-config.js?v=osm-environments-20261125',configUrl);
const {createOsmAuth}=await import('data:text/javascript;base64,'+Buffer.from(authSrc).toString('base64'));
const storage=new Map();
globalThis.sessionStorage={getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
const testAuth=createOsmAuth('test',async()=>'test'),prodAuth=createOsmAuth('prod',async()=>'prod');
storage.set('komorebi:osm-test:token','test-token');
storage.set('komorebi:osm-prod:token','prod-token');
assert.equal(testAuth.readToken(),'test-token');
assert.equal(prodAuth.readToken(),'prod-token');
testAuth.forgetToken();
assert.equal(testAuth.hasToken(),false);
assert.equal(prodAuth.hasToken(),true);
const calls=[];
globalThis.fetch=async (url,options)=>{calls.push({url,options});return {ok:true};};
const test=createOsmApi('test'),prod=createOsmApi('prod');
await test.write('/changeset/create','xml','test-token');
await prod.read('/node/123');
assert.equal(calls[0].url,config.OSM_CONFIG.test.apiOrigin+'/api/0.6/changeset/create');
assert.equal(calls[0].options.headers.Authorization,'Bearer test-token');
assert.equal(calls[1].url,config.OSM_CONFIG.prod.apiOrigin+'/api/0.6/node/123');
assert.equal(calls[1].options.headers.Authorization,undefined);
await assert.rejects(prod.write('/changeset/create','xml','prod-token'));
await assert.rejects(test.write('/../node/123','xml','test-token'));
await assert.rejects(test.read('https://api.openstreetmap.org/api/0.6/node/123'));
assert.equal(calls.length,2);
assert.throws(()=>createOsmApi('live'));
console.log('OSM environment isolation PASS');
